#!/usr/bin/env node
// Tests for scripts/mind-meld-c4.ts — the repo map as a C4 model: folders as containers, files as
// components, declared imports as relationships.

import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import test from 'node:test';
import { validateC4 } from './c4-model.ts';
import { mapToC4 } from './mind-meld-c4.ts';
import type { ModuleFacts } from './mind-meld-langs.ts';

const CLI = join(import.meta.dirname, 'mind-meld.ts');
const module = (file: string, imports: string[] = [], names: string[] = []): ModuleFacts =>
  ({ file, imports, language: file.endsWith('.py') ? 'Python' : 'TypeScript', lines: 3, method: 'test',
    definitions: names.map((name, i) => ({ name, kind: 'function', line: i + 1 })) });

const FACTS = [
  module('web/app.ts', ['web/cart.ts', 'svc/api.py'], ['main']),
  module('web/cart.ts', [], ['total', 'Cart', 'add', 'remove', 'empty', 'count']),
  module('svc/api.py', ['svc/db.py']),
  module('svc/db.py'),
  module('main.ts', ['web/app.ts']),
];

void test('each top-level folder is a container and each source file a component in it', () => {
  const model = mapToC4('shop', FACTS);
  assert.deepEqual(validateC4(model), []);
  assert.equal(model.system.name, 'shop');
  assert.deepEqual(model.elements.filter(element => element.kind === 'container').map(({ id, name, description, technology }) => [id, name, description, technology]), [
    ['c_web', 'web', '2 source files', 'TypeScript'], ['c_svc', 'svc', '2 source files', 'Python'], ['c_root', '(root)', '1 source file', 'TypeScript']]);
  assert.deepEqual(model.elements.find(element => element.id === 'm_web_cart_ts'), {
    id: 'm_web_cart_ts', kind: 'component', parent: 'c_web', name: 'cart.ts', technology: 'TypeScript', source: 'web/cart.ts',
    description: 'Defines total, Cart, add, remove, empty and 1 more' });
  assert.equal(model.elements.find(element => element.id === 'm_svc_db_py')!.description, undefined);
});

void test('each declared import is a relationship between components; there are no dynamic views', () => {
  const model = mapToC4('shop', FACTS);
  assert.deepEqual(model.relationships.map(r => `${r.from} -> ${r.to}: ${r.description}`), [
    'm_web_app_ts -> m_web_cart_ts: imports', 'm_web_app_ts -> m_svc_api_py: imports',
    'm_svc_api_py -> m_svc_db_py: imports', 'm_main_ts -> m_web_app_ts: imports']);
  assert.deepEqual(model.dynamics, []);
});

void test('a big folder groups its components the way the map does', () => {
  const many = Array.from({ length: 13 }, (_, i) => module(`scripts/${i < 7 ? 'queue' : 'loop'}-${i}.ts`));
  const groups = new Set(mapToC4('big', many).elements.flatMap(element => element.group ?? []));
  assert.deepEqual([...groups].sort(), ['loop-*', 'queue-*']);
  assert.equal(mapToC4('shop', FACTS).elements.some(element => element.group), false);
});

function fixture(): string {
  const root = mkdtempSync(join(tmpdir(), 'meld-c4-'));
  execFileSync('git', ['init', '-q'], { cwd: root });
  const files = { 'web/app.ts': "import { total } from './cart.ts';\nexport const main = (): number => total();\n", 'web/cart.ts': 'export function total(): number {\n  return 1;\n}\n' };
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  execFileSync('git', ['add', '.'], { cwd: root });
  return root;
}

void test('mind-meld c4 writes a workspace and a page for a repo', () => {
  const root = fixture(), out = join(root, 'docs', 'c4');
  const run = spawnSync('node', [CLI, 'c4', root, out], { encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
  assert.deepEqual(readdirSync(out).sort(), ['c4.md', 'workspace.dsl']);
  const dsl = readFileSync(join(out, 'workspace.dsl'), 'utf8');
  assert.match(dsl, new RegExp(`^// Generated by scripts/mind-meld\\.ts c4 from the source of ${basename(root)}\\.`));
  assert.match(dsl, /m_web_app_ts -> m_web_cart_ts "imports"/);
  assert.match(dsl, /component c_web "components_c_web"/);
  assert.match(readFileSync(join(out, 'c4.md'), 'utf8'), /c_web\["web<br\/>\[Container: TypeScript\]<br\/>2 source files"\]/);
  rmSync(root, { recursive: true });
});

void test('an import an adapter reports twice is one relationship, and ids that differ only by case stay apart', () => {
  const model = mapToC4('shop', [module('A/b.ts', ['a/b.ts', 'a/b.ts']), module('a/b.ts')]);
  assert.deepEqual(validateC4(model), []);
  assert.deepEqual(model.relationships, [{ from: 'm_A_b_ts', to: 'm_a_b_ts_2', description: 'imports' }]);
});

void test('mind-meld c4 fails clearly without both arguments or without source', () => {
  const usage = spawnSync('node', [CLI, 'c4', '.'], { encoding: 'utf8' });
  assert.equal(usage.status, 1);
  assert.match(usage.stderr, /usage: mind-meld\.ts c4 <repo-root> <out-dir>/);
  const empty = mkdtempSync(join(tmpdir(), 'meld-c4-empty-'));
  execFileSync('git', ['init', '-q'], { cwd: empty });
  const run = spawnSync('node', [CLI, 'c4', empty, join(empty, 'out')], { encoding: 'utf8' });
  assert.equal(run.status, 1);
  assert.match(run.stderr, /no source files in a supported language/);
  rmSync(empty, { recursive: true });
});
