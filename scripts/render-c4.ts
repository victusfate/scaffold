#!/usr/bin/env node
// render-c4 — write the C4 files for every explorer spec that opted in (`"c4": { "system": ... }`).
// Why: clients whose standard is C4 need a Structurizr workspace and C4 views; both are derived from the
// spec, so they are generated and checked, never edited. Per spec it writes <slug>.dsl (the workspace)
// and <slug>.md (the views, drawn with mermaid so GitHub renders them). No model call and no browser.
// A file it wrote earlier for a spec that no longer opts in is removed, and --check reports it.
// Usage:
//   node scripts/render-c4.ts            (or: npm run diagrams:c4)
//   node scripts/render-c4.ts --check    write nothing; exit 1 when a file is missing, stale or left over
//   node scripts/render-c4.ts --specs <dir> --out <dir>   other folders than docs/diagrams/{explorer,c4}

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { explorerToC4 } from './c4-from-explorer.ts';
import { renderC4Markdown } from './c4-mermaid.ts';
import { count } from './c4-model.ts';
import { renderStructurizr } from './c4-structurizr.ts';
import type { ExplorerSpec } from './explorer-spec.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_SUFFIX = '.explorer.json';
const SELF = 'scripts/render-c4.ts';
// How this script signs a workspace and a page, so it only ever removes a file it wrote.
const SIGNED = [`// Generated by ${SELF} `, `by \`${SELF}\`; edit that, not this page.`];

type Files = Record<string, string>;

// The files for one spec: none when it has not opted in, problems instead of files when it cannot convert.
// `specLink` is the path from the output folder to the spec.
function c4Files(slug: string, spec: ExplorerSpec, specLink: string): { files: Files; problems: string[] } {
  if (!spec?.c4) return { files: {}, problems: [] };
  const { model, problems } = explorerToC4(spec);
  if (!model) return { files: {}, problems };
  const workspace = `${slug}.dsl`;
  return { problems: [], files: {
    [workspace]: `${SIGNED[0]}from ${specLink}. Edit the spec, then run it again.\n${renderStructurizr(model)}`,
    [`${slug}.md`]: renderC4Markdown(model, { workspace, from: `[\`${slug}${SPEC_SUFFIX}\`](${specLink}) by \`${SELF}\`` }),
  } };
}

// Every spec in the folder; `converted` counts the specs that produced files. A spec that cannot be read
// is a problem, not a crash.
function renderAll(specs: string, out: string): { files: Files; problems: string[]; converted: number } {
  const all = { files: {} as Files, problems: [] as string[], converted: 0 };
  if (!existsSync(specs)) return { ...all, problems: [`no spec folder at ${specs}`] };
  for (const name of readdirSync(specs).filter(file => file.endsWith(SPEC_SUFFIX)).sort()) {
    const slug = name.slice(0, -SPEC_SUFFIX.length);
    try {
      const spec = JSON.parse(readFileSync(join(specs, name), 'utf8')) as ExplorerSpec;
      const { files, problems } = c4Files(slug, spec, relative(out, join(specs, name)).replace(/\\/g, '/'));
      Object.assign(all.files, files);
      all.problems.push(...problems.map(problem => `${slug}: ${problem}`));
      if (Object.keys(files).length) all.converted++;
    } catch (error) {
      all.problems.push(`${slug}: ${(error as Error).message}`);
    }
  }
  return all;
}

// Files this script wrote earlier that no spec produces now.
function leftOver(files: Files, out: string): string[] {
  if (!existsSync(out)) return [];
  return readdirSync(out).filter(name => /\.(dsl|md)$/.test(name) && !(name in files)
    && SIGNED.some(signature => readFileSync(join(out, name), 'utf8').includes(signature)));
}

// What --check reports: a generated file that is missing or differs, and a left-over one.
function stale(files: Files, out: string): string[] {
  const current = (name: string): boolean => existsSync(join(out, name)) && readFileSync(join(out, name), 'utf8') === files[name];
  return [...Object.keys(files).filter(name => !current(name)).map(name => `${name} is stale: run npm run diagrams:c4`),
    ...leftOver(files, out).map(name => `${name} is left over (its spec no longer opts in): run npm run diagrams:c4`)];
}

function write(files: Files, out: string): void {
  for (const name of leftOver(files, out)) rmSync(join(out, name));
  if (Object.keys(files).length) mkdirSync(out, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text);
}

function main(): number {
  const { values } = parseArgs({ options: { check: { type: 'boolean' }, specs: { type: 'string' }, out: { type: 'string' } } });
  const specs = values.specs ?? join(ROOT, 'docs', 'diagrams', 'explorer'), out = values.out ?? join(ROOT, 'docs', 'diagrams', 'c4');
  const { files, problems, converted } = renderAll(specs, out);
  if (values.check) problems.push(...stale(files, out));
  for (const problem of problems) process.stderr.write(`render-c4: ${problem}\n`);
  if (problems.length) return 1;
  if (values.check) return 0;
  write(files, out);
  process.stdout.write(`render-c4: ${count(converted, 'spec')}, ${count(Object.keys(files).length, 'file')} in ${out}\n`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main());
