#!/usr/bin/env node
// render-c4 — write the C4 files for every explorer spec that opted in (`"c4": { "system": ... }`).
// Why: clients whose standard is C4 need a Structurizr workspace and C4 views; both are derived from the
// spec, so they are generated and checked, never edited. Per spec it writes <slug>.dsl (the workspace)
// and <slug>.md (the views, drawn with mermaid so GitHub renders them). No model call and no browser.
// A file it wrote earlier for a spec that no longer opts in is removed, and --check reports it.
// Usage:
//   node scripts/render-c4.ts            (or: npm run diagrams:c4)
//   node scripts/render-c4.ts --check    write nothing; exit 1 when a file is missing, stale or left over
//   node scripts/render-c4.ts --specs <dir> --out <dir>   other folders than docs/diagrams/{explorer,c4}

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { explorerToC4 } from './c4-from-explorer.ts';
import { renderC4Markdown } from './c4-mermaid.ts';
import { count } from './c4-model.ts';
import { renderStructurizr } from './c4-structurizr.ts';
import type { ExplorerSpec } from './explorer-spec.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_SUFFIX = '.explorer.json';
const SELF = 'scripts/render-c4.ts';
// The first line of each file this script writes. Only a file that starts with it is ever removed, so a
// hand-written file in the output folder, or one that quotes a generated page, is left alone.
const SIGNATURE = { dsl: `// Generated by ${SELF} `, md: `<!-- Generated by ${SELF} ` };

type Files = Record<string, string>;
type Rendered = { files: Files; problems: string[] };

// The files for one spec: none when it has not opted in, problems instead of files when it cannot convert.
// `specLink` is the path from the output folder to the spec.
function c4Files(slug: string, spec: ExplorerSpec, specLink: string): Rendered {
  if (!spec?.c4) return { files: {}, problems: [] };
  const { model, problems } = explorerToC4(spec);
  if (!model) return { files: {}, problems };
  const workspace = `${slug}.dsl`, from = `from ${specLink}. Edit the spec, then run it again.`;
  return { problems: [], files: {
    [workspace]: `${SIGNATURE.dsl}${from}\n${renderStructurizr(model)}`,
    [`${slug}.md`]: `${SIGNATURE.md}${from} -->\n${renderC4Markdown(model, { workspace, from: `[\`${slug}${SPEC_SUFFIX}\`](${specLink}) by \`${SELF}\`` })}`,
  } };
}

// Every spec in the folder. `converted` counts the specs that produced files and `failed` names the ones
// that could not be read or converted: a problem to report, not a crash.
function renderAll(specs: string, out: string): Rendered & { converted: number; failed: string[] } {
  const all = { files: {} as Files, problems: [] as string[], converted: 0, failed: [] as string[] };
  for (const name of readdirSync(specs).filter(file => file.endsWith(SPEC_SUFFIX)).sort()) {
    const slug = name.slice(0, -SPEC_SUFFIX.length);
    let rendered: Rendered;
    try {
      rendered = c4Files(slug, JSON.parse(readFileSync(join(specs, name), 'utf8')) as ExplorerSpec, relative(out, join(specs, name)).replace(/\\/g, '/'));
    } catch (error) {
      rendered = { files: {}, problems: [(error as Error).message] };
    }
    Object.assign(all.files, rendered.files);
    all.problems.push(...rendered.problems.map(problem => `${slug}: ${problem}`));
    if (rendered.problems.length) all.failed.push(slug);
    else if (Object.keys(rendered.files).length) all.converted++;
  }
  return all;
}

// A regular file's text, or undefined when there is none to read (missing, a folder, no permission).
function textOf(path: string): string | undefined {
  try { return statSync(path).isFile() ? readFileSync(path, 'utf8') : undefined; } catch { return undefined; }
}

// Files this script wrote earlier that no spec produces now. A spec that failed keeps its files: it has
// not opted out, it is broken.
function leftOver({ files, failed }: { files: Files; failed: string[] }, out: string): string[] {
  if (!existsSync(out)) return [];
  const signed = (name: string): boolean => {
    const [slug, kind] = name.split(/\.(dsl|md)$/);
    return kind !== undefined && !failed.includes(slug) && (textOf(join(out, name))?.startsWith(SIGNATURE[kind as keyof typeof SIGNATURE]) ?? false);
  };
  return readdirSync(out).filter(name => !(name in files) && signed(name));
}

// What --check reports: a generated file that is missing or differs, and a left-over one.
function stale(rendered: { files: Files; failed: string[] }, out: string): string[] {
  const { files } = rendered;
  return [...Object.keys(files).filter(name => textOf(join(out, name)) !== files[name]).map(name => `${name} is stale: run npm run diagrams:c4`),
    ...leftOver(rendered, out).map(name => `${name} is left over (its spec no longer opts in): run npm run diagrams:c4`)];
}

function write(rendered: { files: Files; failed: string[] }, out: string): void {
  for (const name of leftOver(rendered, out)) rmSync(join(out, name));
  if (Object.keys(rendered.files).length) mkdirSync(out, { recursive: true });
  for (const [name, text] of Object.entries(rendered.files)) writeFileSync(join(out, name), text);
}

function run(): number {
  const { values } = parseArgs({ options: { check: { type: 'boolean' }, specs: { type: 'string' }, out: { type: 'string' } } });
  const specs = values.specs ?? join(ROOT, 'docs', 'diagrams', 'explorer'), out = values.out ?? join(ROOT, 'docs', 'diagrams', 'c4');
  const rendered = renderAll(specs, out), problems = [...rendered.problems, ...(values.check ? stale(rendered, out) : [])];
  for (const problem of problems) process.stderr.write(`render-c4: ${problem}\n`);
  if (problems.length) return 1;
  if (values.check) return 0;
  write(rendered, out);
  process.stdout.write(`render-c4: ${count(rendered.converted, 'spec')}, ${count(Object.keys(rendered.files).length, 'file')} in ${out}\n`);
  return 0;
}

// A bad flag or a folder that cannot be read or written is one line, not a stack trace.
function main(): number {
  try { return run(); } catch (error) {
    process.stderr.write(`render-c4: ${(error as Error).message}\n`);
    return 1;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main());
