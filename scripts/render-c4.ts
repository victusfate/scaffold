#!/usr/bin/env node
// render-c4 — write the C4 files for every explorer spec that opted in (`"c4": { "system": ... }`).
// Why: clients whose standard is C4 need a Structurizr workspace and C4 views; both are derived from the
// spec, so they are generated and checked, never edited. Per spec it writes <slug>.dsl (the workspace)
// and <slug>.md (the views, drawn with mermaid so GitHub renders them). No model call and no browser.
// Usage:
//   node scripts/render-c4.ts            (or: npm run diagrams:c4)
//   node scripts/render-c4.ts --check    write nothing; exit 1 when a file is missing or stale
//   node scripts/render-c4.ts --specs <dir> --out <dir>   other folders than docs/diagrams/{explorer,c4}

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { explorerToC4 } from './c4-from-explorer.ts';
import { renderC4Markdown } from './c4-mermaid.ts';
import { renderStructurizr } from './c4-structurizr.ts';
import { validateSpec, type ExplorerSpec } from './explorer-spec.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_SUFFIX = '.explorer.json';
const SELF = 'scripts/render-c4.ts';

type Rendered = { files: Record<string, string>; problems: string[] };

// The files for one spec: none when it has not opted in, problems instead of files when it cannot convert.
// `specLink` is the path from the output folder to the spec.
export function c4Files(slug: string, spec: ExplorerSpec, specLink: string): Rendered {
  if (!spec.c4) return { files: {}, problems: [] };
  const invalid = validateSpec(spec);
  const { model, problems } = invalid.length ? { model: undefined, problems: invalid } : explorerToC4(spec);
  if (!model) return { files: {}, problems: problems.map(problem => `${slug}: ${problem}`) };
  const workspace = `${slug}.dsl`;
  return { problems: [], files: {
    [workspace]: `// Generated by ${SELF} from ${specLink}. Edit the spec, then run it again.\n${renderStructurizr(model)}`,
    [`${slug}.md`]: renderC4Markdown(model, { workspace, from: `[\`${slug}${SPEC_SUFFIX}\`](${specLink}) by \`${SELF}\`` }),
  } };
}

// Every spec in the folder; `converted` counts the specs that produced files.
function renderAll(specs: string, out: string): Rendered & { converted: number } {
  const all = { files: {} as Record<string, string>, problems: [] as string[], converted: 0 };
  for (const name of readdirSync(specs).filter(file => file.endsWith(SPEC_SUFFIX)).sort()) {
    const spec = JSON.parse(readFileSync(join(specs, name), 'utf8')) as ExplorerSpec;
    const { files, problems } = c4Files(name.slice(0, -SPEC_SUFFIX.length), spec, relative(out, join(specs, name)).replace(/\\/g, '/'));
    Object.assign(all.files, files);
    if (Object.keys(files).length) all.converted++;
    all.problems.push(...problems);
  }
  return all;
}

function main(): number {
  const { values } = parseArgs({ options: { check: { type: 'boolean' }, specs: { type: 'string' }, out: { type: 'string' } } });
  const specs = values.specs ?? join(ROOT, 'docs', 'diagrams', 'explorer'), out = values.out ?? join(ROOT, 'docs', 'diagrams', 'c4');
  const { files, problems, converted } = renderAll(specs, out);
  if (values.check) {
    const current = (name: string): boolean => existsSync(join(out, name)) && readFileSync(join(out, name), 'utf8') === files[name];
    problems.push(...Object.keys(files).filter(name => !current(name)).map(name => `${name} is stale: run npm run diagrams:c4`));
  }
  for (const problem of problems) process.stderr.write(`render-c4: ${problem}\n`);
  if (problems.length || values.check) return problems.length ? 1 : 0;
  const names = Object.keys(files);
  if (names.length) mkdirSync(out, { recursive: true });
  for (const name of names) writeFileSync(join(out, name), files[name]);
  process.stdout.write(`render-c4: ${converted} spec${converted === 1 ? '' : 's'}, ${names.length} files in ${out}\n`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main());
