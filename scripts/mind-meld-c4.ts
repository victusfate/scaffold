// mind-meld-c4 — the static repo map as a C4 model, written as a Structurizr workspace and a C4 page.
// Why: a client whose standard is C4 can start from what their code states instead of a blank model.
// The repo is the described system, each top-level folder a container, each source file a component
// (grouped as the map groups a big folder), and each import declared in source a relationship.
// Facts only, as in the map: no dynamic views, because imports are not observed calls. A folder is only a
// first guess at a container (C4 means a separately running part), so the workspace is meant to be
// extended with `workspace extends`, not edited: it is regenerated.
// Usage: node scripts/mind-meld.ts c4 <repo-root> <out-dir>

import { mkdirSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { renderC4Markdown } from './c4-mermaid.ts';
import { idAllocator, type C4Element, type C4Model } from './c4-model.ts';
import { renderStructurizr } from './c4-structurizr.ts';
import type { ModuleFacts } from './mind-meld-langs.ts';
import { areaOf, groupsOf, inAreaPath, ROOT_AREA, scanRepo } from './mind-meld-map.ts';

const WORKSPACE = 'workspace.dsl';
const PAGE = 'c4.md';
const SELF = 'scripts/mind-meld.ts c4';
// quality-ok: magic-number — definition names in a component's description before "and N more"
const NAMED = 5;

const count = (n: number, noun: string): string => `${n} ${noun}${n === 1 ? '' : 's'}`;

function defines(module: ModuleFacts): string | undefined {
  const names = module.definitions.map(definition => definition.name);
  if (!names.length) return undefined;
  const more = names.length - NAMED;
  return `Defines ${names.slice(0, NAMED).join(', ')}${more > 0 ? ` and ${more} more` : ''}`;
}

export function mapToC4(name: string, facts: ModuleFacts[]): C4Model {
  const allocate = idAllocator(), ids = new Map<string, string>(), elements: C4Element[] = [];
  const areas = new Map<string, ModuleFacts[]>();
  for (const module of facts) areas.set(areaOf(module.file), [...(areas.get(areaOf(module.file)) ?? []), module]);
  for (const [area, modules] of areas) {
    const container = allocate('container', area === ROOT_AREA ? 'root' : area), groups = groupsOf(area, modules);
    elements.push({ id: container, kind: 'container', name: area, description: count(modules.length, 'source file'),
      technology: [...new Set(modules.map(module => module.language))].sort().join(', ') });
    for (const group of groups) for (const module of group.modules) {
      ids.set(module.file, allocate('component', module.file));
      const description = defines(module);
      elements.push({ id: ids.get(module.file)!, kind: 'component', parent: container, name: inAreaPath(module.file, area),
        technology: module.language, source: module.file,
        ...(description ? { description } : {}), ...(groups.length > 1 ? { group: group.label } : {}) });
    }
  }
  // An import of a file the map left out (a test, a vendored file) has no component to point at.
  const relationships = facts.flatMap(module => module.imports.filter(file => ids.has(file) && file !== module.file)
    .map(file => ({ from: ids.get(module.file)!, to: ids.get(file)!, description: 'imports' })));
  return { name, description: `Source files of ${name} by top-level folder, with the imports declared between them. From a static map: no code was run.`,
    system: { name }, elements, relationships, dynamics: [] };
}

// Writes the workspace and the page into outDir; returns the file names written.
export async function writeC4(root: string, outDir: string): Promise<string[]> {
  const facts = await scanRepo(root);
  if (!facts.length) throw new Error('mind-meld c4: no source files in a supported language (add an adapter in .mind-meld/languages)');
  const name = basename(resolve(root)), model = mapToC4(name, facts);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, WORKSPACE), `// Generated by ${SELF} from the source of ${name}. Extend it with "workspace extends"; do not edit it.\n${renderStructurizr(model)}`);
  writeFileSync(join(outDir, PAGE), renderC4Markdown(model, { workspace: WORKSPACE, from: `the source of ${name} by \`${SELF}\`` }));
  return [WORKSPACE, PAGE];
}
