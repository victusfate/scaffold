#!/usr/bin/env bash
# Tests for check-quality-mechanical.sh using fixture files.
set -euo pipefail
PASS=0; FAIL=0
ok()  { echo "  ✓ $1"; PASS=$((PASS + 1)); }
fail(){ echo "  ✗ $1"; FAIL=$((FAIL + 1)); }

SCRIPT=scripts/check-quality-mechanical.sh

[ -f "$SCRIPT" ] || { echo "MISSING: $SCRIPT"; exit 1; }
[ -x "$SCRIPT" ] || { echo "NOT EXECUTABLE: $SCRIPT"; exit 1; }

FIXTURES=$(mktemp -d)
trap 'rm -rf "$FIXTURES"' EXIT
FIXTURE_LINE_COUNT=510   # deliberately over the 500-line limit

# Fixture: clean file (≤500 lines, no magic numbers, no commented-out code)
CLEAN="$FIXTURES/clean.js"
printf 'const MAX_RETRIES = 3;\nfunction run() { return MAX_RETRIES; }\n' > "$CLEAN"

# Fixture: file over 500 lines — comment lines only, no magic-number or commented-code violations
LONG="$FIXTURES/long.js"
for _ in $(seq 1 "$FIXTURE_LINE_COUNT"); do printf '// padding\n'; done > "$LONG"

# Fixture: over-length file blessed by a file-length override pragma — should pass
LONG_OK="$FIXTURES/long-ok.js"
printf '// quality-ok: file-length — one cohesive module, split would fragment it\n' > "$LONG_OK"
for _ in $(seq 1 "$FIXTURE_LINE_COUNT"); do printf '// padding\n'; done >> "$LONG_OK"

# Fixture: file with magic number
MAGIC="$FIXTURES/magic.js"
printf 'function timeout() { return 86400; }\n' > "$MAGIC"

# Fixture: file with commented-out code block
COMMENTED="$FIXTURES/commented.js"
printf '// function old() {\n//   return 1;\n// }\nfunction current() {}\n' > "$COMMENTED"

# Fixture: digits inside a quoted string are data (e.g. a grep pattern), not a magic number
QUOTED="$FIXTURES/quoted.sh"
printf 'grep -qE "Score.*10|10 on all" "$f"\n' > "$QUOTED"

# Fixture: magic number suppressed by pragma on the preceding line
PRAGMA="$FIXTURES/pragma.js"
printf '// quality-ok: magic-number — milliseconds in a day is self-documenting\nconst delay = 86400;\n' > "$PRAGMA"

# Fixture: test file — assertion literals are specs, not thresholds
TESTFILE="$FIXTURES/foo.test.js"
printf 'expect(result).toBe(86400);\n' > "$TESTFILE"

# Fixture: return/exit with a bare number — protocol-defined, not a threshold
RETURN="$FIXTURES/handler.js"
printf 'function notFound() {\n  return 404;\n}\nfunction ok() {\n  return 200;\n}\n' > "$RETURN"

# Fixture: @generated file — skipped whole despite magic numbers (machine-authored data)
GENERATED="$FIXTURES/geometry.ts"
printf '// @generated by image-to-model pipeline — do not edit\nexport const verts = [-5.2, 2.2, 1.3, 86400];\n' > "$GENERATED"

# Fixture: @generated marker AFTER the first 5 lines — must NOT be honored
GENERATED_LATE="$FIXTURES/late.ts"
printf 'const a = 1;\nconst b = 2;\nconst c = 3;\nconst d = 4;\nconst e = 5;\n// @generated\nfunction thresh() { return 86400 + 1; }\n' > "$GENERATED_LATE"

# Fixture: exported named constant — `export const NAME = N` is a named constant (issue #183 item 5)
EXPORTED="$FIXTURES/exported.ts"
printf 'export const DEFAULT_PORT = 8787;\nexport function port() { return DEFAULT_PORT; }\n' > "$EXPORTED"

# Fixture: multi-line UPPER_CASE const initializer — its continuation lines are named values
MULTI="$FIXTURES/multi.ts"
printf 'export const LIMITS = {\n  retries: 30,\n  timeoutMs: 86400,\n};\nfunction f() { return LIMITS; }\n' > "$MULTI"

# Fixture: a magic number AFTER a closed const block is still flagged
MULTI_AFTER="$FIXTURES/multi-after.ts"
printf 'const LIMITS = {\n  retries: 30,\n};\nconst wait = delay(86400);\n' > "$MULTI_AFTER"

# Fixture: a lowercase multi-line object is not a named constant — still flagged
LOWER_MULTI="$FIXTURES/lower-multi.ts"
printf 'const limits = {\n  timeoutMs: 86400,\n};\n' > "$LOWER_MULTI"

# Fixture: a bracket inside a regex/string on a const line must not open a phantom block
PHANTOM="$FIXTURES/phantom.ts"
printf "const OPEN_RE = /\\(/;\nconst OPEN = '{';\nfunction f() { return delay(86400); }\n" > "$PHANTOM"

# Fixture: code after the closing bracket of a const block is still checked
CLOSE_TAIL="$FIXTURES/close-tail.ts"
printf 'const LIMITS = {\n  retries: 30,\n}; const w = delay(86400);\n' > "$CLOSE_TAIL"

# Fixture repo for .quality-ignore: fixtures/ is held back, src/ is not (issue #183 item 6)
IGNORE_REPO="$FIXTURES/ignore-repo"
mkdir -p "$IGNORE_REPO/fixtures/sample" "$IGNORE_REPO/src"
printf '# untrusted sample repos\nfixtures/\n*.vendored.js\n' > "$IGNORE_REPO/.quality-ignore"
printf 'function t() { return 86400 + 1; }\n' > "$IGNORE_REPO/fixtures/sample/bad.js"
printf 'function t() { return 86400 + 1; }\n' > "$IGNORE_REPO/src/lib.vendored.js"
printf 'function t() { return 86400 + 1; }\n' > "$IGNORE_REPO/src/bad.js"

# Clean file should pass
if bash "$SCRIPT" "$CLEAN" > /dev/null 2>&1; then
  ok "clean file passes"
else
  fail "clean file should pass"
fi

# Long file should fail
if bash "$SCRIPT" "$LONG" > /dev/null 2>&1; then
  fail "long file should fail"
else
  ok "long file (>500 lines) fails"
fi

# Long file error includes filename:line citation
output=$(bash "$SCRIPT" "$LONG" 2>&1 || true)
if echo "$output" | grep -qE '(long\.js|long):'; then
  ok "long file citation includes filename"
else
  fail "long file error must include filename:line citation"
fi

# Over-length file with a file-length override pragma should pass
if bash "$SCRIPT" "$LONG_OK" > /dev/null 2>&1; then
  ok "quality-ok: file-length pragma suppresses the length violation"
else
  fail "file-length-overridden file should pass"
fi

# Magic number should fail
if bash "$SCRIPT" "$MAGIC" > /dev/null 2>&1; then
  fail "magic number file should fail"
else
  ok "magic number file fails"
fi

# Magic number error includes filename:line citation
output=$(bash "$SCRIPT" "$MAGIC" 2>&1 || true)
if echo "$output" | grep -qE '(magic\.js|magic):'; then
  ok "magic number citation includes filename"
else
  fail "magic number error must include filename:line citation"
fi

# Commented-out code block should fail
if bash "$SCRIPT" "$COMMENTED" > /dev/null 2>&1; then
  fail "commented-out code file should fail"
else
  ok "commented-out code block fails"
fi

# Commented-out code error includes filename:line citation
output=$(bash "$SCRIPT" "$COMMENTED" 2>&1 || true)
if echo "$output" | grep -qE '(commented\.js|commented):'; then
  ok "commented-out code citation includes filename"
else
  fail "commented-out code error must include filename:line citation"
fi

# Digits inside a quoted string should NOT be flagged as a magic number
if bash "$SCRIPT" "$QUOTED" > /dev/null 2>&1; then
  ok "digits inside a quoted string are not a magic number"
else
  fail "quoted-string digits should not be flagged as a magic number"
fi

# quality-ok: magic-number pragma suppresses the violation on the next line
if bash "$SCRIPT" "$PRAGMA" > /dev/null 2>&1; then
  ok "quality-ok: magic-number pragma suppresses violation"
else
  fail "pragma-suppressed magic number should pass"
fi

# Test files are fully skipped — assertion literals are specs, not thresholds
if bash "$SCRIPT" "$TESTFILE" > /dev/null 2>&1; then
  ok "test file magic numbers are not flagged"
else
  fail "magic numbers in test files should not be flagged"
fi

# return/exit with a bare number should NOT be flagged — protocol-defined values
if bash "$SCRIPT" "$RETURN" > /dev/null 2>&1; then
  ok "return/exit values are not flagged as magic numbers"
else
  fail "return/exit values should not be flagged as magic numbers"
fi

# @generated file is skipped whole — magic numbers in machine-authored data are not flagged
if bash "$SCRIPT" "$GENERATED" > /dev/null 2>&1; then
  ok "@generated file is skipped (machine-authored data)"
else
  fail "@generated file should be skipped"
fi

# @generated marker after the first 5 lines is NOT honored — still flagged
if bash "$SCRIPT" "$GENERATED_LATE" > /dev/null 2>&1; then
  fail "@generated after line 5 should not be honored"
else
  ok "@generated marker only honored in the first 5 lines"
fi

# export const NAME = N is a named constant, not a magic number
if bash "$SCRIPT" "$EXPORTED" > /dev/null 2>&1; then
  ok "export const NAME = N is a named constant"
else
  fail "export const NAME = N should not be flagged"
fi

# Continuation lines of a multi-line UPPER_CASE const initializer are named values
if bash "$SCRIPT" "$MULTI" > /dev/null 2>&1; then
  ok "multi-line UPPER_CASE const initializer is not flagged"
else
  fail "continuation lines of an UPPER_CASE const initializer should not be flagged"
fi

# The const block ends at its closing bracket — later magic numbers are still caught
output=$(bash "$SCRIPT" "$MULTI_AFTER" 2>&1 || true)
if echo "$output" | grep -q 'multi-after.ts:4 '; then
  ok "magic number after a closed const block is still flagged"
else
  fail "magic number after a closed const block should be flagged at line 4 (got: $output)"
fi

# A lowercase multi-line object is not a named constant
if bash "$SCRIPT" "$LOWER_MULTI" > /dev/null 2>&1; then
  fail "lowercase multi-line object should still be flagged"
else
  ok "lowercase multi-line object is still flagged"
fi

# Brackets inside a regex or string literal do not start a multi-line const block
output=$(bash "$SCRIPT" "$PHANTOM" 2>&1 || true)
if echo "$output" | grep -q 'phantom.ts:3 '; then
  ok "bracket inside a regex/string does not hide later magic numbers"
else
  fail "magic number after a regex/string bracket should be flagged at line 3 (got: $output)"
fi

# Code after a block's closing bracket on the same line is still checked
output=$(bash "$SCRIPT" "$CLOSE_TAIL" 2>&1 || true)
if echo "$output" | grep -q 'close-tail.ts:3 '; then
  ok "code after a const block's closing bracket is still checked"
else
  fail "magic number after '};' should be flagged at line 3 (got: $output)"
fi

# .quality-ignore (repo root): dir prefix and * glob skip files; others are still checked
ABS_SCRIPT="$(pwd)/$SCRIPT"
if (cd "$IGNORE_REPO" && bash "$ABS_SCRIPT" fixtures/sample/bad.js src/lib.vendored.js > /dev/null 2>&1); then
  ok ".quality-ignore skips a dir prefix and a * glob"
else
  fail ".quality-ignore should skip fixtures/ and *.vendored.js"
fi
if (cd "$IGNORE_REPO" && bash "$ABS_SCRIPT" src/bad.js > /dev/null 2>&1); then
  fail "files outside .quality-ignore should still be checked"
else
  ok "files outside .quality-ignore are still checked"
fi

echo ""
echo "$PASS passed, $FAIL failed."
[ $FAIL -eq 0 ]
